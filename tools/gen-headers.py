"""Regenerate src/headers.js from sample SAP exports.

Usage: python3 tools/gen-headers.py cji3=<file> zscprg01=<file> zscsrv1=<file> zintc1=<file> mb51=<file> me2n=<file> mb52=<file>

Takes row 1 of the first sheet, keeps the FIRST copy of every repeated caption
(SAP repeats some: BUn, Date, User, Object Type ...). Never commit the sample files.
"""
import sys, json, re, openpyxl

def norm(s):
    return re.sub(r'\s+', ' ', str(s).strip()).lower()

out = {}
for arg in sys.argv[1:]:
    rid, path = arg.split('=', 1)
    ws = openpyxl.load_workbook(path, read_only=True, data_only=True).worksheets[0]
    row = next(ws.iter_rows(min_row=1, max_row=1, values_only=True))
    seen, heads = set(), []
    for h in row:
        if h is None or str(h).strip() == '':
            continue
        k = norm(h)
        if k in seen:
            continue
        seen.add(k)
        heads.append(str(h).strip())
    out[rid] = heads

with open('src/headers.js', 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/gen-headers.py from sample SAP exports (first copy of every caption). Do not edit by hand.\n')
    f.write('var REPORT_HEADERS = ' + json.dumps(out, ensure_ascii=False, indent=1) + ';\n')
    f.write("if (typeof module === 'object' && module.exports) module.exports = REPORT_HEADERS;\n")
print({k: len(v) for k, v in out.items()})
